import java.util.Scanner;

public class Setimo_Codigo {

    public static void main(String[] Args){

        var scanner = new Scanner(System.in);
        System.out.println("Digite aqui o seu primeiro numero: ");
        int numero1 = scanner.nextInt();
        System.out.println("Digite aqui o seu segundo numero: ");
        int numero2 = scanner.nextInt();

        System.out.println("O resultado da sua soma é: "  + (numero1 + numero2));


    }


}
